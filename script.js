function applySiteConfiguration(config){
  const previous=siteConfiguration.contact;
  const next=config.contact;
  ['recruitmentEmail','businessEmail'].forEach(key=>{
    document.querySelectorAll('a[href^="mailto:"]').forEach(anchor=>{
      const oldAddress=anchor.getAttribute('href').slice(7).split('?')[0];
      if(oldAddress!==previous[key])return;
      anchor.href=anchor.getAttribute('href').replace(previous[key],next[key]);
      const strong=anchor.querySelector('strong');
      if(strong)strong.textContent=next[key];
      else anchor.childNodes.forEach(node=>{if(node.nodeType===Node.TEXT_NODE&&node.textContent.includes(previous[key]))node.textContent=node.textContent.replace(previous[key],next[key]);});
    });
  });
  document.querySelectorAll('a[href^="tel:"]').forEach(anchor=>{anchor.href=`tel:+${next.phone.replace(/\D/g,'')}`;const text=anchor.querySelector('strong');if(text)text.textContent=next.phone;});
  document.querySelectorAll('a[href^="https://wa.me/"]').forEach(anchor=>anchor.href=`https://wa.me/${next.whatsapp}`);
  document.getElementById('office-address').textContent=next.address;
  document.getElementById('map-link').href=`https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(next.address.replace(/\n/g,' '))}`;
  const mediaSelectors={logo:'.brand img, .footer-brand img',hero:'.hero-background',about:'.about-main-image',aboutSmall:'.small-image img',careers:'.careers-image>img',banner:'.ocean-banner>img',serviceRecruitment:'.service-card:nth-child(1) .service-photo img',serviceInternational:'.service-card:nth-child(2) .service-photo img',serviceOpportunities:'.service-card:nth-child(3) .service-photo img'};
  Object.entries(mediaSelectors).forEach(([key,selector])=>document.querySelectorAll(selector).forEach(image=>image.src=config.media[key]));
  siteConfiguration=config;
  photographs=config.gallery;
  photoIndex=Math.min(photoIndex,photographs.length-1);
  renderGallery();updateGalleryLanguage();
  toggleGallery.hidden=photographs.length<=5;
  const imageUrl = new URL(config.media.hero, document.baseURI).href;
  document.querySelector('meta[property="og:image"]').content = imageUrl;
  document.querySelector('meta[name="twitter:image"]').content = imageUrl;
  const schema = {'@context':'https://schema.org', '@type':'Organization', name:'PT. Henota Prime Ocean', url:new URL('./', document.baseURI).href, logo:new URL(config.media.logo, document.baseURI).href, telephone:next.phone, email:next.businessEmail, address:{'@type':'PostalAddress', streetAddress:next.address, addressCountry:'ID'}, contactPoint:[{'@type':'ContactPoint', contactType:'recruitment', email:next.recruitmentEmail, availableLanguage:['English','Indonesian']}]};
  document.getElementById('company-schema').textContent = JSON.stringify(schema);
}
