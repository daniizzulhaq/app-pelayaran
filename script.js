function setLanguage(next){
  language = next === 'id' ? 'id' : 'en';
  document.documentElement.lang=language;
  const dictionary=language==='id'?translations.id:english;
  document.querySelectorAll('[data-i18n]').forEach(element=>{
    const key=element.dataset.i18n;
    if(dictionary[key]===undefined)return;
    if(language==='en'){element.innerHTML=dictionary[key];}
    else if(key==='oceanQuote'){
      element.replaceChildren(document.createTextNode('Satu samudra.'),document.createElement('br'));
      const emphasis=document.createElement('em');emphasis.textContent='Kemungkinan tanpa batas.';element.append(emphasis);
    }else if(dictionary[key].includes('\n')){
      const lines=dictionary[key].split('\n');element.replaceChildren();
      lines.forEach((line,index)=>{if(index)element.append(document.createElement('br'));element.append(document.createTextNode(line));});
    }else element.textContent=dictionary[key];
  });
  document.querySelectorAll('[data-placeholder]').forEach(element=>element.placeholder=dictionary[element.dataset.placeholder]||'');
  document.querySelectorAll('[data-lang]').forEach(button=>button.setAttribute('aria-pressed',String(button.dataset.lang===language)));
  document.querySelector('meta[name="description"]').content=language==='id'?'PT. Henota Prime Ocean — Solusi crewing domestik dan internasional. Menghubungkan talenta pelaut Indonesia dengan peluang di samudra dunia.':'PT. Henota Prime Ocean — Global crewing solutions. Connecting Indonesian seafarers with domestic and international maritime opportunities.';
  document.getElementById('lightbox-close').setAttribute('aria-label',language==='id'?'Tutup foto':'Close photograph');
  document.getElementById('lightbox-prev').setAttribute('aria-label',language==='id'?'Foto sebelumnya':'Previous photograph');
  document.getElementById('lightbox-next').setAttribute('aria-label',language==='id'?'Foto berikutnya':'Next photograph');
  updateGalleryLanguage();
  try{localStorage.setItem('hpo-language',language);}catch{}
}
